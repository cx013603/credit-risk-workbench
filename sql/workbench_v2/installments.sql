-- Payment events must have both event/due day strictly before day zero.
-- Unknown or future events are audit only, never used to choose calendars.
CREATE TEMP TABLE INST_eligible AS
SELECT h.* FROM inst_input h JOIN previous_raw p
ON h.SK_ID_PREV=p.SK_ID_PREV AND h.SK_ID_CURR=p.SK_ID_CURR
WHERE p.DAYS_DECISION<0 AND h.DAYS_INSTALMENT<0 AND h.DAYS_ENTRY_PAYMENT<0;
CREATE TEMP TABLE INST_calendar AS
SELECT SK_ID_CURR,SK_ID_PREV,
 COUNT(DISTINCT NUM_INSTALMENT_VERSION) versions,
 MIN(NUM_INSTALMENT_VERSION) min_version,
 bool_and(NUM_INSTALMENT_VERSION IS NOT NULL AND NUM_INSTALMENT_VERSION>0
   AND NUM_INSTALMENT_VERSION=floor(NUM_INSTALMENT_VERSION)) positive_calendar
FROM INST_eligible GROUP BY SK_ID_CURR,SK_ID_PREV;
CREATE TEMP TABLE INST_groups AS
SELECT h.SK_ID_CURR,h.SK_ID_PREV,h.NUM_INSTALMENT_VERSION,h.NUM_INSTALMENT_NUMBER,h.DAYS_INSTALMENT,
 COUNT(*) payments,MAX(h.DAYS_ENTRY_PAYMENT)-h.DAYS_INSTALMENT last_payment_delay
FROM INST_eligible h JOIN INST_calendar c USING(SK_ID_CURR,SK_ID_PREV)
WHERE c.versions=1 AND c.positive_calendar
GROUP BY h.SK_ID_CURR,h.SK_ID_PREV,h.NUM_INSTALMENT_VERSION,h.NUM_INSTALMENT_NUMBER,h.DAYS_INSTALMENT;
CREATE TEMP TABLE INST_group_loan AS
SELECT SK_ID_CURR,SK_ID_PREV,COUNT(*) groups,
 COUNT(*) FILTER(WHERE last_payment_delay>0) late,
 MAX(GREATEST(last_payment_delay,0)) max_delay,
 COUNT(*) FILTER(WHERE payments>1) multi
FROM INST_groups GROUP BY SK_ID_CURR,SK_ID_PREV;
CREATE TEMP TABLE INST_loan AS
SELECT h.SK_ID_CURR,h.SK_ID_PREV,COUNT(*) n,MAX(h.DAYS_ENTRY_PAYMENT) latest,
 CASE WHEN c.versions=1 AND c.positive_calendar THEN 0 ELSE 1 END excluded,
 COALESCE(g.groups,0) groups,COALESCE(g.late,0) late,g.max_delay,COALESCE(g.multi,0) multi
FROM INST_eligible h JOIN INST_calendar c USING(SK_ID_CURR,SK_ID_PREV)
LEFT JOIN INST_group_loan g USING(SK_ID_CURR,SK_ID_PREV)
GROUP BY h.SK_ID_CURR,h.SK_ID_PREV,c.versions,c.positive_calendar,g.groups,g.late,g.max_delay,g.multi;
CREATE TABLE INST_features AS
SELECT SK_ID_CURR,COUNT(*)::BIGINT INST_LOAN_COUNT,SUM(n)::BIGINT INST_PAYMENT_RECORD_COUNT,
 -MAX(latest)::DOUBLE INST_DAYS_SINCE_RECENT_PAYMENT,
 SUM(excluded)::BIGINT INST_EXCLUDED_CALENDAR_LOAN_COUNT,
 SUM(groups)::BIGINT INST_SINGLE_CALENDAR_GROUP_COUNT,
 SUM(late)::DOUBLE/NULLIF(SUM(groups),0) INST_LATE_PAYMENT_GROUP_FRACTION,
 MAX(max_delay)::DOUBLE INST_MAX_PAYMENT_DELAY_DAYS,
 SUM(multi)::DOUBLE/NULLIF(SUM(groups),0) INST_MULTI_PAYMENT_GROUP_FRACTION
FROM INST_loan GROUP BY SK_ID_CURR;
