-- Inherit both parent credit/update day checks from the original bureau policy.
CREATE TEMP TABLE BB_eligible AS
SELECT p.SK_ID_CURR,h.* FROM bb_input h JOIN bureau_raw p USING(SK_ID_BUREAU)
WHERE p.DAYS_CREDIT<0 AND p.DAYS_CREDIT_UPDATE<0 AND h.MONTHS_BALANCE<0;
CREATE TEMP TABLE BB_loan AS
SELECT SK_ID_CURR,SK_ID_BUREAU,COUNT(*) n,MAX(MONTHS_BALANCE) latest,
 COUNT(*) FILTER(WHERE STATUS IN ('0','1','2','3','4','5')) known_active,
 COUNT(*) FILTER(WHERE STATUS IN ('1','2','3','4','5')) delinquent,
 COUNT(*) FILTER(WHERE STATUS IS NULL OR STATUS NOT IN ('0','1','2','3','4','5','C')) unknown,
 COUNT(*) FILTER(WHERE STATUS='C') closed,
 COUNT(*) FILTER(WHERE MONTHS_BALANCE>=-12) last12
FROM BB_eligible GROUP BY SK_ID_CURR,SK_ID_BUREAU;
CREATE TABLE BB_features AS
SELECT SK_ID_CURR,COUNT(*)::BIGINT BB_LOAN_COUNT,SUM(n)::BIGINT BB_MONTH_COUNT,
 -MAX(latest)::DOUBLE BB_MONTHS_SINCE_RECENT,
 SUM(delinquent)::DOUBLE/NULLIF(SUM(known_active),0) BB_DELINQUENT_STATUS_FRACTION,
 SUM(unknown)::DOUBLE/SUM(n) BB_UNKNOWN_STATUS_FRACTION,
 SUM(closed)::DOUBLE/SUM(n) BB_CLOSED_STATUS_FRACTION,
 SUM(last12)::BIGINT BB_LAST12_MONTH_COUNT
FROM BB_loan GROUP BY SK_ID_CURR;
