-- 输入 bureau_input 是 E03 规范表的只读视图；不直接读取 CSV。
-- 时间只有天粒度：同日先后顺序不可证明，因此两种时间均严格 < 0。
CREATE TEMP VIEW bureau_classified AS
SELECT *, CASE
    WHEN DAYS_CREDIT IS NULL THEN 'missing_credit_time'
    WHEN DAYS_CREDIT >= 0 THEN 'credit_not_before'
    WHEN DAYS_CREDIT_UPDATE IS NULL THEN 'missing_update_time'
    WHEN DAYS_CREDIT_UPDATE >= 0 THEN 'update_not_before'
    ELSE 'eligible'
END AS exclusion_reason
FROM bureau_input;

CREATE TEMP VIEW bureau_eligible AS
SELECT * EXCLUDE (exclusion_reason) FROM bureau_classified WHERE exclusion_reason = 'eligible';

CREATE TABLE bureau_features AS
SELECT SK_ID_CURR,
    COUNT(*)::BIGINT AS BUREAU_ELIGIBLE_COUNT,
    1::BIGINT AS BUREAU_HAS_ELIGIBLE_HISTORY,
    -MAX(DAYS_CREDIT) AS BUREAU_DAYS_SINCE_MOST_RECENT,
    COUNT(*) FILTER (WHERE CREDIT_CURRENCY = 'currency 1') AS BUREAU_C1_COUNT,
    COUNT(*) FILTER (WHERE CREDIT_CURRENCY <> 'currency 1') AS BUREAU_OTHER_CURRENCY_COUNT,
    COUNT(*) FILTER (WHERE CREDIT_CURRENCY IS NULL) AS BUREAU_CURRENCY_MISSING_COUNT,
    COUNT(*) FILTER (WHERE CREDIT_CURRENCY = 'currency 1' AND AMT_CREDIT_SUM >= 0) AS BUREAU_C1_AMOUNT_AVAILABLE_COUNT,
    COUNT(*) FILTER (WHERE CREDIT_CURRENCY = 'currency 1' AND (AMT_CREDIT_SUM IS NULL OR AMT_CREDIT_SUM < 0)) AS BUREAU_C1_AMOUNT_UNAVAILABLE_COUNT,
    SUM(AMT_CREDIT_SUM) FILTER (WHERE CREDIT_CURRENCY = 'currency 1' AND AMT_CREDIT_SUM >= 0) AS BUREAU_C1_CREDIT_SUM,
    AVG(AMT_CREDIT_SUM) FILTER (WHERE CREDIT_CURRENCY = 'currency 1' AND AMT_CREDIT_SUM >= 0) AS BUREAU_C1_CREDIT_MEAN,
    MAX(AMT_CREDIT_SUM) FILTER (WHERE CREDIT_CURRENCY = 'currency 1' AND AMT_CREDIT_SUM >= 0) AS BUREAU_C1_CREDIT_MAX,
    COUNT(*) FILTER (WHERE CREDIT_ACTIVE = 'Active') AS BUREAU_ACTIVE_COUNT,
    COUNT(*) FILTER (WHERE CREDIT_ACTIVE = 'Closed') AS BUREAU_CLOSED_COUNT,
    COUNT(*) FILTER (WHERE CREDIT_ACTIVE = 'Sold') AS BUREAU_SOLD_COUNT,
    COUNT(*) FILTER (WHERE CREDIT_ACTIVE = 'Bad debt') AS BUREAU_BAD_DEBT_COUNT,
    COUNT(*) FILTER (WHERE CREDIT_ACTIVE IS NULL OR CREDIT_ACTIVE NOT IN ('Active','Closed','Sold','Bad debt')) AS BUREAU_OTHER_STATUS_COUNT,
    (COUNT(*) FILTER (WHERE CREDIT_ACTIVE = 'Active'))::DOUBLE / COUNT(*) AS BUREAU_ACTIVE_FRACTION
FROM bureau_eligible
GROUP BY SK_ID_CURR;
